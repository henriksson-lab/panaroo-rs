//! NCBI genetic code tables.
//!
//! # Provenance
//!
//! **This is not Panaroo code.** It is data belonging to another package, kept in its own
//! file per the project rule that third-party code lives separately with its source
//! recorded.
//!
//! Transcribed from `Bio.Data.CodonTable.generic_by_id` in
//! [Biopython](https://biopython.org/) 1.84 (Biopython License Agreement /
//! BSD 3-Clause). Biopython in turn transcribes the NCBI genetic code tables,
//! <https://www.ncbi.nlm.nih.gov/Taxonomy/Utils/wprintgc.cgi>.
//!
//! Generated mechanically from the installed Biopython rather than typed by hand, so the
//! values match the library the reference Python actually uses. Regenerate with the
//! snippet in `tests/parity/types/` if the pinned Biopython version changes.
//!
//! See `NOTICE.md`.
//!
//! # What Panaroo uses
//!
//! `prokka.py::get_trans_table` reads three fields of `generic_by_id[table]`:
//! `forward_table` (codon -> amino acid), `stop_codons`, and `start_codons`. Each table
//! here carries exactly those. Entries containing `U` (the RNA spellings) are retained
//! because Panaroo filters them itself with `if 'U' in codon: continue` — dropping them
//! here would be a silent behavioural change.

/// One NCBI genetic code, reduced to the fields `get_trans_table` reads.
pub struct CodonTable {
    /// `tb.forward_table` — codon to single-letter amino acid, in Biopython's iteration
    /// order.
    pub forward_table: &'static [(&'static str, char)],
    /// `tb.stop_codons`
    pub stop_codons: &'static [&'static str],
    /// `tb.start_codons`
    pub start_codons: &'static [&'static str],
}

/// `Bio.Data.CodonTable.generic_by_id[id]`; `None` if the table does not exist, which
/// `get_trans_table` turns into a `RuntimeError`.
pub fn generic_by_id(id: i64) -> Option<&'static CodonTable> {
    TABLES.iter().find(|(i, _)| *i == id).map(|(_, t)| t)
}

